/**
 * Private repositories: the client-side crypto core (`docs/security/private-repos.md`).
 *
 * WebCrypto only (AES-256-GCM, HKDF-SHA256, HMAC-SHA256, SHA-256), with every subkey
 * non-extractable; the `repoKey` wrap goes through the evo-sdk `encryptedFor` facade the
 * caller passes in. The Rust twin is `crates/forge-core/src/private.rs`; the `private_*`
 * conformance vectors in `forge-contracts/vectors/` hold the two byte-for-byte in parity
 * (`conformance.test.ts`). Deterministic seal variants for those vectors live in
 * `./testing`, which this module deliberately does not re-export (ESLint bans importing it
 * outside tests); `__unsafe*` symbols of `./doc`, `./pack` and `./release` are likewise not
 * re-exported. `./named` is the specific-people letter (`enc` v0x04); `sealMembersDoc` the
 * members-only (`enc` v0x03) seal of a public repository's lane. `./blind` and `./members-ref` are the blinded OIDs of members-only
 * branches and pull requests (§19; `sealMembersRef`'s fixed-salt twin is test-only). `./bundle` and `./convert` are
 * a repository made public's readers (§18): its conversion facts and the keys its owner published;
 * `./key-letter` is the kind-10 key letter (§20): typed keys sealed to specific people, and the `branch` letter
 * that shares one members-only branch as it is now; `./read-letter` the `read` letter a request to a bot carries and
 * `./access-notice` a bot's kind-11 access notice (§22). `./branch-key` is a narrower branch's own key (DESIGN §4.3, phase 3F):
 * its generations, its ref updates (`enc` v0x06) and packs (DFPK 0x03), the `branchKey` letter and
 * the fold of those letters into a `BranchRing` (`sealBranchRef`'s and `sealBranchPack`'s fixed twins are test-only); `./bot-post` is a bot's members-only post (`enc` v0x05, §23)
 * and the `postKey` letter a maintainer sends the bot. `./bundle` also reads and writes a maintainer's make-public bundle (DESIGN §4.6), whose entries
 * publish one document revision's per-object key (`membersObjKey`, `letterObjKey`) and open it
 * with no other key (`openMembersWithKey`, `openLetterWithKey`). `./release`'s `sealRelease` and `sealReleaseManifest` are, since the web writes
 * sealed releases (`private-repos.md` §16.8, `lib/repo/sealed-release.ts`): both draw hedged
 * randomness, and only their fixed-nonce twins stay test-only.
 */

