const a1 = approve(ps[0].seed, ps[0].keys, ROOM, state, pid1);
const a3 = approve(ps[2].seed, ps[2].keys, ROOM, state, pid1);
const a2only = approve(ps[1].seed, ps[1].keys, ROOM, state, pid2);
const rej = reject(ps[2].keys, ROOM, pid2, 'not now');
const afterOne = reduce([...messages, a1]);
