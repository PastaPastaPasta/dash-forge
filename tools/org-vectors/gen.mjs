import { resolve } from 'node:path';
const dti = (p) => import(pathToFileURL(resolve(process.argv[2], p)).href);
const { people, runCeremony, MNEMONICS } = await dti('test/helpers.mjs');
const { reduce } = await dti('src/state.mjs');
const { approve, combine, propose, recoverShares, reject, recordBroadcast } = await dti('src/participant.mjs');
const { envelopeId, sealEnvelope } = await dti('src/envelope.mjs');
const { canonical, digest, hex, utf8 } = await dti('src/util.mjs');
const { publicShareOf } = await dti('src/ceremony.mjs');
const ROOM = 't_000102030405060708090a0b0c0d0e0f';
const ps = people(3);
const base = runCeremony(ps, { room: ROOM, threshold: 2, label: 'Forge vector org' });
